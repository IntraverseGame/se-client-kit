import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { toTypeAliases, withoutReferenceNotes } from "./generate-contracts.ts";
import { operationRoutes } from "./play-routes.ts";

const generatedSnapshotTypes = (): string =>
  readFileSync(
    join(
      import.meta.dirname,
      "..",
      "packages",
      "contracts",
      "src",
      "generated",
      "snapshot.ts",
    ),
    "utf8",
  );

const generatedPlayTypes = (): string =>
  readFileSync(
    join(
      import.meta.dirname,
      "..",
      "packages",
      "contracts",
      "src",
      "generated",
      "play.ts",
    ),
    "utf8",
  );

const note = (name: string): string =>
  ` * This interface was referenced by \`undefined\`'s JSON-Schema\n * via the \`definition\` "${name}".\n`;

describe("toTypeAliases", () => {
  it("rewrites an exported interface as a type alias", () => {
    expect(
      toTypeAliases(
        "/** A comment. */\nexport interface Amount {\nvalue: string\n}\n",
      ),
    ).toBe("/** A comment. */\nexport type Amount = {\nvalue: string\n}\n");
  });

  it("leaves type aliases and property text untouched", () => {
    const source =
      'export type RoundId = string\nexport type Step = {\nkind: "export interface X {"\n}\n';
    expect(toTypeAliases(source)).toBe(source);
  });

  it("fails on an interface that extends another", () => {
    expect(() =>
      toTypeAliases("export interface B extends A {\nb: string\n}\n"),
    ).toThrow("cannot rewrite as a type alias: export interface B extends A {");
  });

  it("leaves no interface in the committed Snapshot types", () => {
    expect(generatedSnapshotTypes()).not.toMatch(/^export interface /mu);
  });

  it("leaves no interface in the committed Play API types", () => {
    expect(generatedPlayTypes()).not.toMatch(/^export interface /mu);
  });
});

describe("withoutReferenceNotes", () => {
  it("drops a doc comment that holds only reference notes", () => {
    expect(
      withoutReferenceNotes(
        `/**\n${note("Theme")} * \n${note("Theme")} */\nexport type Theme = {\n}\n`,
      ),
    ).toBe("export type Theme = {\n}\n");
  });

  it("keeps the description of a doc comment", () => {
    expect(
      withoutReferenceNotes(
        `/**\n * UUIDv7.\n * \n${note("RoundId")} * \n${note("RoundId")} */\nexport type RoundId = string\n`,
      ),
    ).toBe("/**\n * UUIDv7.\n */\nexport type RoundId = string\n");
  });

  it("fails on a reference note in another shape", () => {
    expect(() =>
      withoutReferenceNotes(
        "/**\n * This schema was referenced by `x`'s JSON-Schema.\n */\n",
      ),
    ).toThrow("cannot drop the reference note");
  });

  it("leaves no reference note in the committed Snapshot types", () => {
    expect(generatedSnapshotTypes()).not.toMatch(/was referenced by/u);
  });
});

describe("the committed Play API types", () => {
  it.each([
    "redeemLaunchCode",
    "refreshPlayToken",
    "startRound",
    "continueRound",
    "cashOutRound",
    "cancelRound",
    "getSnapshot",
  ])("type the %s operation", operationId => {
    expect(generatedPlayTypes()).toMatch(
      new RegExp(`^  ${operationId}: \\{$`, "mu"),
    );
  });

  it("name the document they were generated from", () => {
    expect(generatedPlayTypes()).toMatch(
      /^\/\/ Generated by tools\/generate-contracts\.ts from src\/schemas\/play\.v1\.openapi\.yaml\./u,
    );
  });
});

/** The member names of the generated Play API type `name`. */
const memberNames = (name: string): string[] => {
  const block =
    new RegExp(`^export type ${name} = \\{\\n([\\s\\S]*?)^\\};$`, "mu").exec(
      generatedPlayTypes(),
    )?.[1] ?? "";
  return [...block.matchAll(/^ {2}([A-Za-z0-9_]+): \{/gmu)].map(
    match => match[1] ?? "",
  );
};

const pathsOf = (members: string): string =>
  `export type paths = {\n${members}};\n`;

describe("operationRoutes", () => {
  it("reads each operation's path and method, by operationId", () => {
    expect(
      operationRoutes(
        pathsOf(
          '  "/a": {\n    /** A. */\n    post: operations["one"];\n  };\n  "/b": {\n    get: operations["two"];\n  };\n',
        ),
      ),
    ).toBe(
      '/** Each operation\'s path and method, by `operationId`, read from `paths`. */\nexport type operationRoutes = {\n  one: { path: "/a"; method: "post" };\n  two: { path: "/b"; method: "get" };\n};\n',
    );
  });

  it("fails on a method it cannot read", () => {
    expect(() =>
      operationRoutes(
        pathsOf('  "/a": {\n    post: { inline: true };\n  };\n'),
      ),
    ).toThrow("cannot read the route of");
  });

  it("fails on an operation served twice", () => {
    expect(() =>
      operationRoutes(
        pathsOf(
          '  "/a": {\n    post: operations["one"];\n  };\n  "/b": {\n    post: operations["one"];\n  };\n',
        ),
      ),
    ).toThrow("served twice");
  });

  it("fails without paths", () => {
    expect(() => operationRoutes("export type x = {};\n")).toThrow(
      "no `paths`",
    );
  });

  it("have exactly the keys of the generated operations", () => {
    expect(memberNames("operationRoutes").toSorted()).toEqual(
      memberNames("operations").toSorted(),
    );
    expect(memberNames("operations").length).toBeGreaterThan(0);
  });

  it("are in the committed Play API types, one per operation", () => {
    expect(generatedPlayTypes()).toContain(
      '  continueRound: { path: "/play/v1/rounds:continue"; method: "post" };',
    );
    expect(generatedPlayTypes()).toContain(
      '  getSnapshot: { path: "/play/v1/snapshot"; method: "get" };',
    );
  });
});
