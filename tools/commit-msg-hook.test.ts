import { spawnSync } from "node:child_process";
import {
  chmodSync,
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { devNull, tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, describe, expect, it } from "vitest";

// The commit-msg hook (.githooks/commit-msg, installed with `pnpm hooks`): it
// refuses a commit message that credits an AI tool or an agent. The hook runs
// as git runs it (executed, with the message file as its argument), and inside
// real `git commit` runs in temporary repositories, without any user or system
// git configuration. Three cases guard the hook's shape: it fails closed when
// it cannot read the message; a long message is read whole (a pipe whose
// reader stops early lets the writer's SIGPIPE pass it under pipefail); and the
// diff that `git commit -v` appends below the scissors line is not message.
// Each pattern has a case that only it refuses.

const root = join(import.meta.dirname, "..");
const HOOK = ".githooks/commit-msg";
const hook = join(root, HOOK);
const REFUSAL =
  "commit-msg: AI or agent attribution is not allowed in commit messages.";
const TRAILER = "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>";

const directories: string[] = [];
afterEach(() => {
  for (const directory of directories.splice(0)) {
    rmSync(directory, { recursive: true, force: true });
  }
});

const temporary = (): string => {
  const directory = mkdtempSync(join(tmpdir(), "se-client-kit-commit-msg-"));
  directories.push(directory);
  return directory;
};

const environment = (home: string, locale = "C"): NodeJS.ProcessEnv => ({
  PATH: process.env["PATH"],
  HOME: home,
  LC_ALL: locale,
  GIT_CONFIG_GLOBAL: devNull,
  GIT_CONFIG_NOSYSTEM: "1",
  GIT_EDITOR: "true",
  GIT_AUTHOR_NAME: "test",
  GIT_AUTHOR_EMAIL: "test@example.invalid",
  GIT_AUTHOR_DATE: "2026-01-01T00:00:00Z",
  GIT_COMMITTER_NAME: "test",
  GIT_COMMITTER_EMAIL: "test@example.invalid",
  GIT_COMMITTER_DATE: "2026-01-01T00:00:00Z",
});

type Outcome = { readonly status: number | null; readonly stderr: string };

/** Runs the hook on `message`, as git does: executed, the file its argument. */
const runHook = (message: string, locale: string): Outcome => {
  const directory = temporary();
  const file = join(directory, "COMMIT_EDITMSG");
  writeFileSync(file, message);
  const result = spawnSync(hook, [file], {
    cwd: directory,
    env: environment(directory, locale),
    encoding: "utf8",
  });
  return { status: result.status, stderr: result.stderr };
};

const REFUSED: ReadonlyArray<readonly [string, string]> = [
  ["a Claude co-author trailer", `Add the notes\n\n${TRAILER}\n`],
  [
    "a Claude Code line",
    "Add the notes\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n",
  ],
  [
    "a bot co-author",
    "Add the notes\n\nCo-authored-by: copilot[bot] <copilot@example.invalid>\n",
  ],
  ["a Generated with AI line", "Generated with AI\n"],
  // One pattern each: the address alone, an AI co-author, a bot co-author.
  ["the address alone", "Fix the noreply@anthropic.com handling\n"],
  [
    "an AI co-author",
    "Add the notes\n\nCo-authored-by: AI Assistant <x@example.invalid>\n",
  ],
  [
    "any bot co-author",
    "Add the notes\n\nCo-authored-by: helper[bot] <bot@example.invalid>\n",
  ],
  [
    "a trailer near the top of a 20,000-line message",
    `Add the notes\n\n${TRAILER}\n\n${Array.from(
      { length: 20_000 },
      (_, line) => `Line ${line} of a long body, to fill the pipe.\n`,
    ).join("")}`,
  ],
];

const PASSED: ReadonlyArray<readonly [string, string]> = [
  [
    "a human co-author",
    "Add the notes\n\nCo-authored-by: Jane Doe <jane@example.com>\n",
  ],
  // Names that only contain a tool's word: each word is matched whole.
  [
    "a co-author whose name contains ai",
    "Add the notes\n\nCo-authored-by: Kai Smith <kai@example.com>\n",
  ],
  [
    "a co-author whose name contains aider",
    "Add the notes\n\nCo-authored-by: Haider Ali <h@example.com>\n",
  ],
  [
    "a co-author whose name contains gpt",
    "Add the notes\n\nCo-authored-by: Egpt Person <e@example.com>\n",
  ],
  [
    "prose about a generated file",
    "Refresh the mocks; the client\ngenerated by mockgen, which maintains its own list, changed.\n",
  ],
  [
    "a comment-only message",
    `# Please enter the commit message for your changes.\n# ${TRAILER}\n`,
  ],
  ["an empty message", ""],
];

// The C locale, and a UTF-8 one (the emoji line is multibyte there).
describe.each(["C", "C.UTF-8"])("the hook in the %s locale", locale => {
  it.each(REFUSED)("refuses %s", (_, message) => {
    const outcome = runHook(message, locale);
    expect(outcome.stderr).toContain(REFUSAL);
    expect(outcome.status).toBe(1);
  });

  it.each(PASSED)("passes %s", (_, message) => {
    const outcome = runHook(message, locale);
    expect(outcome.stderr).toBe("");
    expect(outcome.status).toBe(0);
  });

  it("refuses, with a non-zero exit, a message it cannot read", () => {
    const directory = temporary();
    const result = spawnSync(hook, [join(directory, "missing")], {
      cwd: directory,
      env: environment(directory, locale),
      encoding: "utf8",
    });
    expect(result.status).not.toBe(0);
    expect(result.status).not.toBeNull();
  });
});

type Repository = {
  readonly directory: string;
  readonly git: (...args: string[]) => ReturnType<typeof spawnSync>;
};

/**
 * A repository with one commit, the hook copied to `.githooks/` with its mode,
 * and the root `hooks` script run in it, as a contributor runs `pnpm hooks`.
 */
const repository = (): Repository => {
  const directory = temporary();
  const env = environment(directory);
  const git = (...args: string[]): ReturnType<typeof spawnSync> =>
    spawnSync("git", args, { cwd: directory, env, encoding: "utf8" });
  expect(git("init", "--quiet").status).toBe(0);
  mkdirSync(join(directory, ".githooks"));
  copyFileSync(hook, join(directory, HOOK));
  chmodSync(join(directory, HOOK), statSync(hook).mode);
  const manifest = JSON.parse(
    readFileSync(join(root, "package.json"), "utf8"),
  ) as { scripts: Record<string, string> };
  const install = spawnSync(
    "sh",
    ["-c", manifest.scripts["hooks"] ?? "false"],
    {
      cwd: directory,
      env,
      encoding: "utf8",
    },
  );
  expect(install.status).toBe(0);
  writeFileSync(join(directory, "README.md"), "notes\n");
  expect(git("add", "README.md").status).toBe(0);
  expect(git("commit", "--quiet", "-m", "Start the notes").status).toBe(0);
  return { directory, git };
};

describe("the hook in a real git commit", () => {
  it("refuses a commit whose message carries an attribution", () => {
    const { git } = repository();
    expect(git("commit", "--allow-empty", "-m", "Add", "-m", TRAILER)).toEqual(
      expect.objectContaining({
        status: 1,
        stderr: expect.stringContaining(REFUSAL) as unknown,
      }),
    );
  });

  it("passes `git commit -v` whose staged diff, below the scissors, has the address", () => {
    const { directory, git } = repository();
    writeFileSync(
      join(directory, "README.md"),
      "notes\nWrite to noreply@anthropic.com for nothing.\n",
    );
    expect(git("add", "README.md").status).toBe(0);
    const commit = git("commit", "--quiet", "-v", "-e", "-m", "Add a line");
    expect(commit.stderr).toBe("");
    expect(commit.status).toBe(0);
    expect(git("log", "-1", "--format=%B").stdout).toBe("Add a line\n\n");
  });
});

describe("the hook's installation", () => {
  it("is executable, and tracked as executable once in the index", () => {
    expect(statSync(hook).mode & 0o111).toBe(0o111);
    // A fresh checkout gets the index's mode, so CI checks the tracked mode
    // through the line above; once staged, the index entry is checked here
    // too (no entry before the file is first staged).
    const entry = spawnSync("git", ["ls-files", "--stage", "--", HOOK], {
      cwd: root,
      encoding: "utf8",
    }).stdout;
    expect(["", "100755"]).toContain(entry.split(" ")[0]);
  });

  it("is installed by a plain `hooks` script, not a lifecycle or wireit one", () => {
    const manifest = JSON.parse(
      readFileSync(join(root, "package.json"), "utf8"),
    ) as {
      scripts: Record<string, string>;
      wireit: Record<string, unknown>;
    };
    expect(manifest.scripts["hooks"]).toBe(
      "git config core.hooksPath .githooks",
    );
    expect(manifest.wireit["hooks"]).toBeUndefined();
    for (const lifecycle of [
      "prepare",
      "preinstall",
      "install",
      "postinstall",
    ]) {
      expect(manifest.scripts[lifecycle]).toBeUndefined();
    }
  });
});
